/**
 * Regenerates public/sitemap.xml from src/site/content/seo.js.
 *
 * The route list lives in one place so the sitemap, the prerendered HTML
 * shells and the pages themselves cannot disagree. Run `npm run sitemap`
 * after adding a route or a blog post.
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const { ROUTE_SEO, SITE_URL } = await import(
  pathToFileURL(join(appRoot, 'src/site/content/seo.js')).href
);
const { POSTS } = await import(
  pathToFileURL(join(appRoot, 'src/site/content/posts.js')).href
);

const PRIORITY = {
  '/': '1.0',
  '/about': '0.8',
  '/blog': '0.8',
  '/contact': '0.7',
  '/ride-with-us': '0.7',
};
const FREQUENCY = { '/': 'weekly', '/blog': 'weekly' };

const urls = [
  ...Object.keys(ROUTE_SEO).map((path) => ({
    path,
    priority: PRIORITY[path] || '0.4',
    frequency: FREQUENCY[path] || 'monthly',
  })),
  ...POSTS.map((post) => ({
    path: `/blog/${post.slug}`,
    priority: '0.6',
    frequency: 'yearly',
  })),
];

const body = urls
  .map(
    ({ path, priority, frequency }) =>
      `  <url>\n    <loc>${SITE_URL}${path}</loc>\n    <changefreq>${frequency}</changefreq>\n    <priority>${priority}</priority>\n  </url>`
  )
  .join('\n');

await writeFile(
  join(appRoot, 'public/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- Generated by scripts/build-sitemap.mjs from src/site/content/seo.js.\n     Run \`npm run sitemap\` after adding a route or a blog post. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`,
  'utf8'
);

console.log(`sitemap: ${urls.length} urls`);
